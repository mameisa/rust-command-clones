use regex::Regex;

/*
 * Rust Regex 学習メモ
 *
 * パターン         意味                  例
 * ----------------------------------------------------
 * grep             文字列そのもの        "grep"
 *
 * .                任意の1文字          "gr.p"
 *                  grep, grap, gr1p
 *
 * *                直前文字の0回以上     "ab*"
 *                  a, ab, abb, abbb
 *
 * +                直前文字の1回以上     "ab+"
 *                  ab, abb, abbb
 *
 * ?                直前文字の0回/1回     "ab?"
 *                  a, ab
 *
 * ^                行頭                 "^grep"
 *                  grepで始まる行
 *
 * $                行末                 "grep$"
 *                  grepで終わる行
 *
 * 例:
 *
 * "^grep$"
 *   → 行全体が "grep"
 *
 * "^grep"
 *   → grepで始まる
 *
 * "grep$"
 *   → grepで終わる
 *
 * "gr.p"
 *   → grep, grap, gr1pなどに一致
 *
 * Rustでは regex crate を使用する
 *
 * use regex::Regex;
 *
 * let re = Regex::new("^grep$").unwrap();
 * let result = re.is_match("grep");
 */


 /*
 * Rust Regex 学習メモ
 *
 * 基本記号
 * ----------------------------------------------------
 * grep             文字列そのもの
 *
 * .                任意の1文字
 *                  例) gr.p
 *                  → grep, grap, gr1p
 *
 * *                直前文字の0回以上
 *                  例) ab*
 *                  → a, ab, abb, abbb
 *
 * +                直前文字の1回以上
 *                  例) ab+
 *                  → ab, abb, abbb
 *
 * ?                直前文字の0回または1回
 *                  例) ab?
 *                  → a, ab
 *
 * ^                行頭
 *                  例) ^grep
 *                  → grepで始まる行
 *
 * $                行末
 *                  例) grep$
 *                  → grepで終わる行
 *
 * ----------------------------------------------------
 * 文字クラス
 * ----------------------------------------------------
 *
 * [abc]
 *   → a,b,c のどれか1文字
 *
 * 例:
 *   [abc]
 *
 * 一致:
 *   a
 *   b
 *   c
 *
 * 不一致:
 *   d
 *
 * ----------------------------------------------------
 *
 * [a-z]
 *   → 小文字アルファベット1文字
 *
 * 一致:
 *   a
 *   g
 *   z
 *
 * 不一致:
 *   A
 *   1
 *
 * ----------------------------------------------------
 *
 * [0-9]
 *   → 数字1文字
 *
 * 一致:
 *  
 * 
 *  * ----------------------------------------------------
 *
 * [a-z]+
 *   → 小文字アルファベットが1文字以上連続
 *
 * 分解すると
 *
 *   [a-z]
 *     → 小文字アルファベット1文字
 *
 *   +
 *     → 直前パターンの1回以上繰り返し
 *
 * つまり
 *
 *   [a-z]+
 *
 * は
 *
 *   小文字アルファベットが1文字以上続く文字列
 *
 * を意味する。
 *
 * 一致:
 *   a
 *   abc
 *   grep
 *   rust
 *
 * 不一致:
 *   123
 *   ABC
 *   _abc
 *
 * 部分一致:
 *   abc123
 *     → "abc" が一致
 *
 *   123abc
 *     → "abc" が一致
 *
 * ----------------------------------------------------
 *
 * [0-9]+
 *   → 数字が1文字以上連続
 *
 * 一致:
 *   1
 *   123
 *   987654
 *
 * 不一致:
 *   abc
 *
 * ----------------------------------------------------
 *
 * [a-zA-Z]+
 *   → 英字(大文字・小文字)が1文字以上連続
 *
 * 一致:
 *   ABC
 *   abc
 *   Rust
 *
 * ----------------------------------------------------
 *
 * ^[a-z]+$
 *   → 行全体が小文字アルファベットのみ
 *
 * 一致:
 *   grep
 *   rust
 *
 * 不一致:
 *   grep123
 *   123grep
 *   Rust
 *
 * ----------------------------------------------------

 * */


fn is_regex_match(pattern: &str, line: &str) -> bool{
    let re = Regex::new(pattern).unwrap();
    re.is_match(line)
}

fn main(){

    println!(
        "{}",
        is_regex_match("gr.p", "gr1p")
    );

}